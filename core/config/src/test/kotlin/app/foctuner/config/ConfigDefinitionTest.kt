package app.foctuner.config

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class ConfigDefinitionTest {
    private val mcconf = BundledDefinitions.load("7.01", ConfigKind.MCCONF)
    private val appconf = BundledDefinitions.load("7.01", ConfigKind.APPCONF)

    private fun xml(params: String, ser: String, groups: String = "") =
        """<?xml version="1.0" encoding="UTF-8"?><ConfigParams><Params>$params</Params><SerOrder>$ser</SerOrder><Grouping>$groups</Grouping></ConfigParams>"""

    @Test
    fun crc32cMatchesTheStandardCheckValue() {
        assertEquals(0xE3069283L, Crc32c.compute("123456789".toByteArray()))
    }

    @Test
    fun bundledSignaturesMatchTheFirmwareConstants() {
        // MCCONF_SIGNATURE and APPCONF_SIGNATURE in vedderb/bldc confgenerator.h at e22727a, generated by VESC Tool.
        assertEquals(471314414L, mcconf.signature)
        assertEquals(2802465283L, appconf.signature)
    }

    @Test
    fun signatureIsBuiltFromNameTypeWireTypeAndEnumNames() {
        val def = ConfigXmlParser.parse(
            xml(
                "<a><type>2</type><vTx>1</vTx></a>" +
                    "<e><type>4</type><enumNames>X</enumNames><enumNames>Y</enumNames></e>" +
                    "<unsent><type>2</type><vTx>1</vTx></unsent>",
                "<ser>a</ser><ser>e</ser>",
            ),
        )
        assertEquals(Crc32c.compute("a21e40XY".toByteArray()), def.signature)
        assertEquals(1571022139L, def.signature)
    }

    @Test
    fun signatureHashesUtf8() {
        val def = ConfigXmlParser.parse(xml("<ä><type>1</type><vTx>9</vTx></ä>", "<ser>ä</ser>"))
        assertEquals(Crc32c.compute("ä19".toByteArray(Charsets.UTF_8)), def.signature)
    }

    @Test
    fun bundledDefinitionsHaveTheExpectedShape() {
        assertEquals(214, mcconf.params.size)
        assertEquals(205, mcconf.serialized.size)
        assertEquals(124, appconf.params.size)
        assertEquals(123, appconf.serialized.size)

        val byType = mcconf.params.values.groupingBy { it.type }.eachCount()
        assertEquals(
            mapOf(
                ParamType.DOUBLE to 141, ParamType.INT to 34, ParamType.STRING to 4,
                ParamType.ENUM to 24, ParamType.BOOL to 8, ParamType.BITFIELD to 3,
            ),
            byType,
        )
        assertEquals(
            setOf("motor_brand", "motor_model", "motor_weight", "motor_sensor_type", "motor_description"),
            mcconf.params.keys.filter { it.startsWith("motor_") && it !in mcconf.serializeOrder && !it.contains("quality") }.toSet(),
        )
        assertEquals(listOf("new_parameter"), appconf.params.keys.filter { it !in appconf.serializeOrder })
    }

    @Test
    fun parsesParameterFields() {
        val pwm = mcconf.param("pwm_mode")
        assertEquals(ParamType.ENUM, pwm.type)
        assertEquals(ParamValue.IntValue(1), pwm.default)
        assertEquals(listOf("Nonsynchronous HISW", "Synchronous", "Bipolar"), pwm.enumNames)
        assertEquals("MCCONF_PWM_MODE", pwm.cDefine)

        val current = mcconf.param("l_current_max")
        assertEquals(ParamType.DOUBLE, current.type)
        assertEquals(WireType.DOUBLE32_AUTO, current.wire)
        assertEquals(1000.0, current.wireScale)
        assertEquals(ParamValue.DoubleValue(60.0), current.default)
        assertEquals(0.0, current.minDouble)
        assertEquals(5000.0, current.maxDouble)
        assertEquals(" A", current.suffix)
        assertEquals("Motor Current Max", current.longName)
        assertTrue(current.description.startsWith("<!DOCTYPE HTML"))

        val hall = mcconf.param("hall_table__0")
        assertEquals(WireType.INT8, hall.wire)
        assertEquals(-1L, hall.minInt)
        assertEquals(6L, hall.maxInt)
        assertEquals(ParamValue.IntValue(-1), hall.default)

        val brand = mcconf.param("motor_brand")
        assertEquals(ParamType.STRING, brand.type)
        assertEquals(ParamValue.TextValue(""), brand.default)
        assertFalse(brand.transmittable)

        assertEquals(WireType.UINT32, appconf.param("timeout_msec").wire)
        assertEquals(ParamType.UNDEFINED, appconf.param("new_parameter").type)
    }

    @Test
    fun parsesGroupingWithSeparators() {
        assertEquals(
            listOf("General", "BLDC", "DC", "FOC", "PID Controllers", "Additional Info"),
            mcconf.groups.map { it.name },
        )
        assertEquals(
            listOf("General", "Sensors", "Current", "Voltage", "RPM", "Wattage", "Temperature", "BMS", "Advanced"),
            mcconf.groups.first().subgroups.map { it.name },
        )
        for (def in listOf(mcconf, appconf)) {
            val entries = def.groups.flatMap { g -> g.subgroups.flatMap { it.entries } }
            assertEquals(16, entries.count { it is GroupEntry.Separator })
            assertTrue(entries.none { it is GroupEntry.Param && it.name.startsWith("::sep::") })
        }
        assertTrue(mcconf.groups.flatMap { it.subgroups }.any { "l_current_max" in it.paramNames })
    }

    @Test
    fun bundledLoaderCachesAndRejectsUnknownVersions() {
        assertTrue(BundledDefinitions.load("7.01", ConfigKind.MCCONF) === mcconf)
        assertFailsWith<IllegalArgumentException> { BundledDefinitions.load("5.00", ConfigKind.MCCONF) }
    }

    @Test
    fun rejectsUnknownElementsAndBadNumbers() {
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(xml("<a><type>2</type><surprise>1</surprise></a>", "<ser>a</ser>"))
        }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(xml("<a><type>two</type></a>", ""))
        }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(xml("<a><type>9</type></a>", ""))
        }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse("<ConfigParams><Params></Params></ConfigParams>")
        }
        assertFailsWith<ConfigDefinitionException> { ConfigXmlParser.parse("<ConfigParams><Params>") }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse("<!DOCTYPE x [<!ENTITY a \"b\">]><ConfigParams/>")
        }
    }

    @Test
    fun rejectsLayoutsThatCannotBeSerialized() {
        val int = "<a><type>2</type><vTx>1</vTx></a>"
        assertFailsWith<ConfigDefinitionException> { ConfigXmlParser.parse(xml(int, "<ser>missing</ser>")) }
        assertFailsWith<ConfigDefinitionException> { ConfigXmlParser.parse(xml(int, "<ser>a</ser><ser>a</ser>")) }
        assertFailsWith<ConfigDefinitionException> { ConfigXmlParser.parse(xml(int + int, "")) }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(xml("<a><type>0</type></a>", "<ser>a</ser>"))
        }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(xml("<a><type>1</type><vTx>3</vTx></a>", "<ser>a</ser>"))
        }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(xml("<a><type>2</type><vTx>8</vTx></a>", "<ser>a</ser>"))
        }
        assertFailsWith<ConfigDefinitionException> {
            ConfigXmlParser.parse(
                xml(
                    int, "<ser>a</ser>",
                    "<group><groupName>g</groupName><subgroup><subgroupName>s</subgroupName>" +
                        "<subgroupParams><param>nope</param></subgroupParams></subgroup></group>",
                ),
            )
        }
    }
}
