#!/usr/bin/env python3
"""Extracts the wire layout the firmware actually uses from its generated confgenerator.c.

Usage: gen_config_layout.py CONFGENERATOR_C OUT_DIR SOURCE_NOTE

Writes mcconf.layout and appconf.layout into OUT_DIR, one line per serialized parameter in wire order:
`name kind [scale]` with kind one of u8 i8 u16 i16 u32 i32 f16 f32 f32auto. The firmware's deserializer is used
because it tells signed from unsigned bytes. Array members `a[2]` are written as `a__2`, the XML's spelling.
"""
import re
import sys
from pathlib import Path

PATTERNS = [
    (re.compile(r"^buffer\[ind\+\+\]$"), lambda m: "u8"),
    (re.compile(r"^\(int8_t\)buffer\[ind\+\+\]$"), lambda m: "i8"),
    (re.compile(r"^buffer_get_(u?int(?:16|32))\(buffer, &ind\)$"), lambda m: m.group(1).replace("uint", "u").replace("int", "i")),
    (re.compile(r"^buffer_get_float(16|32)\(buffer, ([0-9.]+), &ind\)$"), lambda m: f"f{m.group(1)} {m.group(2)}"),
    (re.compile(r"^buffer_get_float32_auto\(buffer, &ind\)$"), lambda m: "f32auto"),
]
STATEMENT = re.compile(r"^conf->([A-Za-z0-9_.\[\]]+) = (.*);$")


def layout(source: str, name: str) -> list[str]:
    body = re.search(r"bool confgenerator_deserialize_%s\(.*?\n}\n" % name, source, re.S)
    if body is None:
        sys.exit(f"no deserializer for {name}")
    lines = []
    for raw in body.group(0).splitlines():
        line = raw.strip()
        if not line.startswith("conf->"):
            continue
        statement = STATEMENT.match(line)
        if statement is None:
            sys.exit(f"cannot parse: {line}")
        field = re.sub(r"\[(\d+)\]", r"__\1", statement.group(1))
        for pattern, kind in PATTERNS:
            match = pattern.match(statement.group(2))
            if match:
                lines.append(f"{field} {kind(match)}")
                break
        else:
            sys.exit(f"unknown encoding: {line}")
    return lines


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    source = Path(sys.argv[1]).read_text()
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for name in ("mcconf", "appconf"):
        header = f"# Generated by core/config/tools/gen_config_layout.py\n# Source: {sys.argv[3]}\n"
        (out / f"{name}.layout").write_text(header + "\n".join(layout(source, name)) + "\n")


main()
