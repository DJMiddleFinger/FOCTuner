#!/usr/bin/env python3
"""Generate CommPacketId.kt from the firmware's datatypes.h.

Usage: tools/gen_comm_ids.py path/to/bldc/datatypes.h > core/protocol/src/main/kotlin/app/foctuner/protocol/CommPacketId.kt

Re-run when targeting a newer firmware; the ids are append-only upstream.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
block = re.search(r"typedef enum \{(?P<body>[^}]*COMM_FW_VERSION[^}]*)\}\s*COMM_PACKET_ID;", src, re.S)
if not block:
    sys.exit("COMM_PACKET_ID enum not found")

entries = []
for line in block.group("body").splitlines():
    m = re.match(r"\s*(COMM_\w+)\s*=\s*(\d+)\s*,?", line)
    if m:  # commented-out entries start with // and are skipped
        entries.append((m.group(1), int(m.group(2))))

ids = [i for _, i in entries]
assert len(set(ids)) == len(ids), "duplicate command ids"

print("// GENERATED by tools/gen_comm_ids.py from the firmware's datatypes.h. Do not edit by hand.")
print("package app.foctuner.protocol")
print()
print("/** Command ids (first payload byte) of the VESC packet protocol. */")
print("enum class CommPacketId(val id: Int) {")
for name, i in entries:
    print(f"    {name}({i}),")
print("    ;")
print()
print("    companion object {")
print("        private val byId = entries.associateBy { it.id }")
print()
print("        /** Null for ids this build doesn't know (newer firmware). */")
print("        fun fromId(id: Int): CommPacketId? = byId[id]")
print("    }")
print("}")
